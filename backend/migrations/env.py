"""Alembic environment.

Key decisions:

1. The URL comes from DATABASE_URL, falling back to the same SQLite default the
   app uses. A migration must be runnable by a developer who has never set an
   environment variable, and must never embed a credential in the repo.

2. `render_as_batch` is enabled for SQLite. SQLite cannot ALTER most column
   properties in place, so Alembic has to rebuild the table; batch mode does
   that correctly instead of emitting DDL SQLite will reject.

3. `compare_type` and `compare_server_default` are on, so an autogenerated
   migration catches a changed column type -- a silent schema drift that
   otherwise only shows up as data corruption later.
"""

from __future__ import annotations

import os
import sys
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

# Make `app` importable when alembic is invoked from backend/.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.db import Base  # noqa: E402
from app import models  # noqa: E402,F401  (registers every mapper)

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)


def _database_url() -> str:
    url = os.environ.get("DATABASE_URL", "")
    if url:
        return url
    default = os.path.join(os.path.expanduser("~"), "compliance-os.db")
    return "sqlite:///" + os.environ.get("COMPLIANCE_DB", default)


def _is_sqlite(url: str) -> bool:
    return url.startswith("sqlite")


config.set_main_option("sqlalchemy.url", _database_url())
target_metadata = Base.metadata


def run_migrations_offline() -> None:
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        render_as_batch=_is_sqlite(url),
        compare_type=True,
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
        future=True,
    )
    url = config.get_main_option("sqlalchemy.url")
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            render_as_batch=_is_sqlite(url),
            compare_type=True,
            compare_server_default=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
